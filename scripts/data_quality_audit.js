/* --------------------------------- run ---------------------------------- */

(async () => {
  const results = [];
  for (const d of DECLARED) {
    const file = path.join(FIX, d.file);
    if (!fs.existsSync(file)) {
      console.error(`[skip] ${d.file} missing`);
      continue;
    }
    const candles = d.load(file);
    if (d.allowSpecialSessions) {
      // documented relaxation: this fixture intentionally contains non-standard session windows
    }
    const audit = await auditDataset(candles, d.provenance, {
      minBarsForResearch: d.minBarsForResearch,
    });
    // Special-session fixtures: session-window deviations are expected, so drop that blocker.
    if (d.allowSpecialSessions) {
      audit.blockers = audit.blockers.filter((b) => !/outside the 09:15-15:30/.test(b));
      audit.researchUsable = audit.blockers.length === 0;
      audit.stats.outsideSessionBars = audit.stats.outsideSessionBars; // retained for transparency
    }
    results.push({ expectFailure: !!d.expectFailure, ...audit });
    console.error(
      `[audit] ${audit.provenance.id.padEnd(26)} rows=${String(audit.rows).padStart(5)} grade=${audit.grade} score=${String(audit.qualityScorePct).padStart(5)}% usable=${audit.researchUsable} profitClaim=${audit.profitClaimAllowed} ${audit.checksum.algorithm}:${audit.checksum.value.slice(0, 12)}…`,
    );
  }

  /* ---------------- negative controls: prove each check fires ---------------- */
  const base = parseJson(path.join(FIX, "sample_nifty50_1m.json"));
  const day = base[0].t;
  const prov = (id, kind, source) => ({
    id,
    kind,
    instrument: "CONTROL",
    timeframe: "1m",
    source,
    retrievedOrGeneratedAt: "2026-11-17",
    timezone: "Asia/Kolkata",
    adjustments: "none",
    limitations: ["negative control"],
  });

  const controls = [];
  const addControl = async (id, candles, expectBlocker, opts = {}) => {
    const a = await auditDataset(candles, prov(id, "SYNTHETIC", "negative control fixture"), { minBarsForResearch: 10, ...opts });
    // A control is "detected" if the condition shows up either as a blocking reason or as a
    // recorded anomaly (some dimensions, e.g. zero-volume share, are reported but not blocking).
    const hit = a.blockers.some((b) => expectBlocker.test(b)) || a.anomalies.some((x) => expectBlocker.test(x.type) || expectBlocker.test(x.message));
    controls.push({ id, expectedDetection: expectBlocker.source, detected: hit, blockers: a.blockers, anomalyTypes: [...new Set(a.anomalies.map((x) => x.type))] });
    console.error(`[control] ${id.padEnd(24)} detected=${hit}`);
  };

  await addControl("CTRL_duplicate", [...base.slice(0, 50), { ...base[49] }, ...base.slice(50)], /duplicate/i);
  await addControl("CTRL_unordered", [...base.slice(0, 50), base[60], base[55], ...base.slice(50)], /unordered/i);
  await addControl("CTRL_invalid_ohlc", [...base.slice(0, 50), { t: day + 50 * 60000, o: 100, h: 90, l: 110, c: 95, v: 10 }, ...base.slice(51)], /INVALID_OHLC|invalid/i);
  await addControl("CTRL_zero_volume", base.map((c, i) => (i < 40 ? { ...c, v: 0 } : c)), /ZERO_VOLUME|volume/i);
  await addControl("CTRL_stale", base.map((c, i) => (i >= 20 && i < 60 ? { ...c, o: base[19].o, h: base[19].h, l: base[19].l, c: base[19].c } : c)), /STALE_REPEAT|stale/i);
  // a holiday-dated bar: 2026-01-26 is Republic Day (declared exchange holiday)
  const holidayMs = Date.parse("2026-01-26T10:00:00+05:30");
  await addControl("CTRL_holiday", [...base.slice(0, 30), { t: holidayMs, o: 100, h: 101, l: 99, c: 100, v: 10 }, ...base.slice(30)], /holiday/i);
  await addControl("CTRL_outside_session", [...base.slice(0, 30), { t: Date.parse("2026-02-18T20:30:00+05:30"), o: 100, h: 101, l: 99, c: 100, v: 10 }, ...base.slice(30)], /outside the 09:15-15:30|OUTSIDE_SESSION/i);
  await addControl("CTRL_too_few_bars", base.slice(0, 5), /minimum/i);

  /* provisional-as-real guard */
  let guardCaught = false;
  try {
    assertProvenanceConsistent(prov("CTRL_fake_real", "REAL", "synthetic GBM seed=42"));
  } catch {
    guardCaught = true;
  }
  controls.push({ id: "CTRL_synthetic_labelled_real", expectedDetection: "provenance guard throws", detected: guardCaught });

  /* checksum determinism */
  const fp1 = await fingerprintCandles(base);
  const fp2 = await fingerprintCandles(base);
  const fpReordered = await fingerprintCandles([...base].reverse());
  controls.push({
    id: "CTRL_checksum_determinism",
    expectedDetection: "identical data -> identical checksum; different order -> different checksum",
    detected: fp1.value === fp2.value && fp1.value !== fpReordered.value,
  });

  /* ------------------------------- outputs -------------------------------- */
  const registry = {
    schemaVersion: "1.0.0",
    generatedAt: new Date().toISOString(),
    policy: {
      realDataAvailable: false,
      note: "No REAL market data is available in this environment. Every dataset below is SYNTHETIC, INCOMPLETE or UNVERIFIED. Synthetic data must never be presented as real market data and cannot support profitability claims.",
      profitClaimRule: "profitClaimAllowed is true only for kind=REAL datasets that pass every quality check.",
      minBarsForResearch: 200,
    },
    datasets: results.map((r) => ({
      id: r.provenance.id,
      kind: r.provenance.kind,
      instrument: r.provenance.instrument,
      timeframe: r.provenance.timeframe,
      source: r.provenance.source,
      retrievedOrGeneratedAt: r.provenance.retrievedOrGeneratedAt,
      timezone: r.provenance.timezone,
      adjustments: r.provenance.adjustments,
      limitations: r.provenance.limitations,
      rows: r.rows,
      sessions: r.sessions,
      dateRange: r.dateRange,
      checksum: r.checksum,
      qualityScorePct: r.qualityScorePct,
      grade: r.grade,
      researchUsable: r.researchUsable,
      profitClaimAllowed: r.profitClaimAllowed,
      blockers: r.blockers,
      stats: r.stats,
    })),
  };

  const auditOut = {
    generatedAt: new Date().toISOString(),
    command: "node scripts/data_quality_audit.js",
    datasets: results,
    negativeControls: controls,
    controlsAllDetected: controls.every((c) => c.detected),
  };

  fs.writeFileSync(OUT_REG, JSON.stringify(registry, null, 2) + "\n");
  fs.writeFileSync(OUT_AUDIT, JSON.stringify(auditOut, null, 2) + "\n");

  /* registry invariants — these must hold for every committed registry */
  const invariants = {
    // No REAL data exists in this environment, so nothing may claim to be REAL.
    noUnsubstantiatedRealClaims: registry.datasets.every((d) => d.provenance_kind_ok !== false && (d.kind === "REAL" ? d.source && d.adjustments && d.retrievedOrGeneratedAt : true)),
    // Profitability claims are only permitted for REAL, fully-validated datasets.
    noProfitClaimsOnSynthetic: registry.datasets.every((d) => !(d.profitClaimAllowed && d.kind !== "REAL")),
    // Every dataset carries a checksum, provenance and quality grade.
    everyDatasetHasChecksum: registry.datasets.every((d) => d.checksum && d.checksum.value && d.checksum.rows === d.rows),
    everyDatasetHasProvenance: registry.datasets.every((d) => d.source && d.timezone && d.retrievedOrGeneratedAt && d.limitations.length > 0),
    // A corrupted dataset must never be research-usable.
    corruptedNotUsable: registry.datasets.every((d) => (d.grade === "F" || d.qualityScorePct < 70 ? !d.researchUsable : true)),
    // At least one dataset is available for research.
    hasUsableDataset: registry.datasets.some((d) => d.researchUsable),
  };
  const invariantsOk = Object.values(invariants).every(Boolean);
  auditOut.invariants = invariants;
  auditOut.invariantsOk = invariantsOk;
  fs.writeFileSync(OUT_AUDIT, JSON.stringify(auditOut, null, 2) + "\n");

  console.log(
    JSON.stringify(
      {
        registry: OUT_REG,
        datasets: registry.datasets.map((d) => ({ id: d.id, kind: d.kind, rows: d.rows, grade: d.grade, score: d.qualityScorePct, usable: d.researchUsable, profitClaim: d.profitClaimAllowed })),
        controlsAllDetected: auditOut.controlsAllDetected,
        invariantsOk,
        controls: controls.map((c) => ({ id: c.id, detected: c.detected })),
      },
      null,
      2,
    ),
  );
  process.exitCode = auditOut.controlsAllDetected && invariantsOk ? 0 : 1;
})();
